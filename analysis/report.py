"""The Markdown summary of Parts 2-4 written by the pipeline (``outputs/report.md``)."""

from __future__ import annotations

from collections.abc import Sequence

import pandas as pd

from analysis.responders import Cohort, format_p
from analysis.subsets import CountQuestion, SampleFilter
from analysis.theme import RESPONSE_LABELS, SEX_LABELS, population_label


def markdown_table(df: pd.DataFrame, right_align: Sequence[str] = ()) -> str:
    """Render a (pre-formatted) DataFrame as a GitHub-flavoured Markdown table."""
    header = "| " + " | ".join(df.columns) + " |"
    rule = "|" + "|".join("---:" if col in right_align else "---" for col in df.columns) + "|"
    body = ["| " + " | ".join(str(value) for value in row) + " |" for row in df.itertuples(index=False)]
    return "\n".join([header, rule, *body])


def _pct(value: float) -> str:
    return f"{value:.2f}"


def _signed(value: float) -> str:
    return f"{value:+.2f}".replace("-", "−")  # typographic minus sign


def render_report(
    *,
    n_samples: int,
    population_summary: pd.DataFrame,
    cohort: Cohort,
    cohort_counts: pd.DataFrame,
    results: pd.DataFrame,
    by_timepoint: pd.DataFrame,
    findings: list[str],
    sample_filter: SampleFilter,
    subset: pd.DataFrame,
    per_project: pd.DataFrame,
    by_response: pd.DataFrame,
    by_sex: pd.DataFrame,
    b_cell_question: CountQuestion,
    b_cells: pd.DataFrame,
) -> str:
    counts = cohort_counts.set_index("response")
    b_cell_answer = b_cells.iloc[0]
    summary = pd.DataFrame(
        {
            "population": population_summary["population"],
            "mean %": population_summary["mean"].map(_pct),
            "median %": population_summary["median"].map(_pct),
            "IQR %": [f"{a:.2f}–{b:.2f}" for a, b in zip(population_summary["q1"], population_summary["q3"])],
            "range %": [f"{a:.2f}–{b:.2f}" for a, b in zip(population_summary["min"], population_summary["max"])],
        }
    )
    stats_table = pd.DataFrame(
        {
            "population": results["population"],
            "median % (R)": results["median_responders"].map(_pct),
            "median % (NR)": results["median_non_responders"].map(_pct),
            "difference, pp (95% CI)": [
                f"{_signed(d)} ({_signed(lo)} to {_signed(hi)})"
                for d, lo, hi in zip(results["lmm_difference"], results["lmm_ci_low"], results["lmm_ci_high"])
            ],
            "mixed-model p": results["lmm_p"].map(format_p),
            "q (FDR)": results["lmm_q"].map(format_p),
            "Mann–Whitney p": results["mwu_p"].map(format_p),
            "MWU q": results["mwu_q"].map(format_p),
            "AUC": results["auc"].map(lambda v: f"{v:.3f}"),
            "significant (mixed model)": results["significant"].map({True: "**yes**", False: "no"}),
        }
    )
    timepoint_p = by_timepoint.pivot(index="population", columns="timepoint", values="mwu_p")
    timepoint_p = timepoint_p.reindex(results["population"])
    timepoint_table = pd.DataFrame(
        {"population": timepoint_p.index, **{f"day {t} p": timepoint_p[t].map(format_p) for t in timepoint_p.columns}}
    )
    per_project_table = per_project.rename(columns={"n_samples": "samples"})
    response_table = pd.DataFrame(
        {
            "response": by_response["response"].map(lambda v: f"{RESPONSE_LABELS.get(v, 'not applicable')} ({v})"),
            "subjects": by_response["n_subjects"],
        }
    )
    sex_table = pd.DataFrame(
        {"sex": by_sex["sex"].map(lambda v: f"{SEX_LABELS.get(v, 'unknown')} ({v})"), "subjects": by_sex["n_subjects"]}
    )

    lines = [
        "# Miraclib immune-profiling results",
        "",
        "_Generated by `make pipeline` (`run_analysis.py`) from `cell_counts.db`. Do not edit by hand._",
        "",
        "## Part 2 – Relative frequency of each population per sample",
        "",
        f"`part2_cell_frequencies.csv` has one row per sample and population ({n_samples:,} samples × "
        f"{len(population_summary)} populations = {n_samples * len(population_summary):,} rows) with columns "
        "`sample, total_count, population, count, percentage`, where `total_count` is the sum of the five "
        "populations in the sample and `percentage` = 100 × `count` / `total_count`.",
        "",
        "Distribution of each population's relative frequency across all samples:",
        "",
        markdown_table(summary, right_align=summary.columns[1:]),
        "",
        "## Part 3 – Responders vs non-responders",
        "",
        f"Cohort: {cohort.describe()}. {counts.loc['yes', 'n_subjects']:,} responders "
        f"({counts.loc['yes', 'n_samples']:,} samples) and {counts.loc['no', 'n_subjects']:,} non-responders "
        f"({counts.loc['no', 'n_samples']:,} samples); every patient was sampled on days 0, 7 and 14.",
        "",
        "### Findings",
        "",
        *[f"- {finding}" for finding in findings],
        "",
        "![Boxplots of relative frequency by response](part3_boxplots.png)",
        "",
        "### Statistics per population",
        "",
        markdown_table(stats_table, right_align=stats_table.columns[1:-1]),
        "",
        "R = responders, NR = non-responders, pp = percentage points (responders − non-responders).",
        "",
        "Method: for each population, a linear mixed-effects model "
        "`percentage ~ responder + C(timepoint) + (1 | patient)` estimates the difference in mean relative "
        "frequency between responders and non-responders while accounting for the three samples per "
        "patient; p-values are adjusted across the five populations with the Benjamini–Hochberg false "
        "discovery rate, and a population is called significant at q < 0.05. A two-sided Mann–Whitney U "
        "test on the sample-level frequencies (the data in the boxplots) is a secondary, distribution-free "
        "check, adjusted the same way; AUC is the probability that a random responder sample has the higher "
        "frequency (0.5 = no separation). The two tests measure different things (a difference in mean "
        "frequency vs. a tendency for one group's values to rank higher), so they need not agree; where only "
        "the primary test survives correction, the evidence should be read as moderate, not conclusive.",
        "",
        "### By timepoint (exploratory)",
        "",
        "Two-sided Mann–Whitney U p-values (unadjusted) comparing responders and non-responders at each "
        "timepoint. A predictor of response would have to differ at baseline (day 0).",
        "",
        markdown_table(timepoint_table, right_align=timepoint_table.columns[1:]),
        "",
        "## Part 4 – Baseline subset",
        "",
        f"Filter: {sample_filter.describe()} (`condition = '{sample_filter.condition}'`, "
        f"`treatment = '{sample_filter.treatment}'`, `sample_type = '{sample_filter.sample_type}'`, "
        f"`time_from_treatment_start = {sample_filter.timepoint}`): **{len(subset):,} samples** from "
        f"**{len(subset[['project', 'subject']].drop_duplicates()):,} subjects**. The sample list is in "
        "`part4_baseline_samples.csv`.",
        "",
        "Samples per project:",
        "",
        markdown_table(per_project_table, right_align=["samples"]),
        "",
        "Subjects by response:",
        "",
        markdown_table(response_table, right_align=["subjects"]),
        "",
        "Subjects by sex:",
        "",
        markdown_table(sex_table, right_align=["subjects"]),
        "",
        f"### Average {population_label(b_cell_question.population)}: male melanoma responders at baseline",
        "",
        "Considering melanoma males of all sample and treatment types, the average number of B cells for "
        f"responders at time = 0 is **{b_cell_answer['mean_count']:.2f}** "
        f"({b_cell_answer['n_samples']:,} samples from {b_cell_answer['n_subjects']:,} subjects; "
        f"filter: {b_cell_question.describe()}). Result in "
        "`part4_avg_b_cells_melanoma_male_responders.csv`.",
        "",
    ]
    return "\n".join(lines)
